import { test, expect } from '@playwright/test'
import { fixture } from './reader-fixture.mjs'

test('导入、分册、翻页、划线与刷新恢复', async ({page}) => {
  await page.goto('/')
  await expect(page.getByRole('heading',{name:'我的书架'})).toBeVisible()
  await page.getByLabel('选择 EPUB 文件').setInputFiles(await fixture())
  await expect(page.getByRole('heading',{name:'窗边读本'})).toBeVisible()
  await page.getByLabel('每册页数').selectOption('20')
  const cards = page.locator('.volume')
  await expect(cards.nth(1)).toBeVisible()
  await cards.first().click()
  await expect(page.locator('.sheet')).toHaveCount(2)
  await expect(page.getByRole('button',{name:'上一页',exact:true})).toBeDisabled()
  await expect(page.getByRole('img',{name:'窗景'})).toBeVisible()
  const para = page.locator('.sheet .page-text p').first()
  await para.evaluate(el => {
    const range=document.createRange(), text=el.querySelector('span').firstChild
    range.setStart(text,0);range.setEnd(text,4)
    const sel=getSelection();sel.removeAllRanges();sel.addRange(range)
    el.dispatchEvent(new PointerEvent('pointerup',{bubbles:true}))
  })
  await page.getByLabel('批注内容').fill('这句话')
  await page.getByRole('button',{name:'高亮',exact:true}).click()
  await expect(page.locator('.page-text .mark').first()).toBeVisible()
  await page.getByLabel('折角书签').click()
  await expect(page.getByLabel('折角书签')).toHaveAttribute('aria-pressed','true')
  await page.keyboard.press('ArrowRight')
  await expect(page.locator('.sheet footer').first()).toHaveText('3')
  await page.getByLabel('声景混音').click()
  await page.getByLabel('雨声',{exact:true}).focus()
  await page.keyboard.press('ArrowRight')
  await expect(page.getByLabel('雨声',{exact:true})).toHaveValue('0.01')
  await expect(page.locator('.sheet footer').first()).toHaveText('3')
  await page.keyboard.press('Escape')
  await page.reload()
  await expect(cards.first()).toContainText('读至第 3 页')
  await cards.first().click()
  await expect(page.locator('.sheet footer').first()).toHaveText('3')
  await page.getByRole('button',{name:'上一页',exact:true}).click()
  await expect(page.getByLabel('折角书签')).toHaveAttribute('aria-pressed','true')
  await expect(page.locator('.page-text .mark').first()).toHaveAttribute('title','这句话')
  await page.getByLabel('目录',{exact:true}).click()
  await page.getByRole('button',{name:'归鸟',exact:true}).click()
  await expect(page.getByRole('dialog',{name:'本册已读完'})).toBeVisible()
  await page.getByRole('button',{name:'回到书架'}).click()
  await expect(cards.last()).toContainText('已读完')
  await page.setViewportSize({width:390,height:740})
  await cards.first().click()
  await expect(page.locator('.sheet')).toHaveCount(1)
  expect(await page.evaluate(()=>document.documentElement.scrollHeight<=innerHeight)).toBeTruthy()
})
